/* =========================================================================
 * ctf.js  ·  r00tp4rv CTF engine
 * =========================================================================
 *
 * Everything security relevant about the CTF lives here, on purpose, so it
 * can be read and audited without wading through terminal UI code.
 *
 * DESIGN NOTE FOR THE CURIOUS (hello, source hunter)
 * --------------------------------------------------
 * There are no flags in this file. There is no sudo password in this file.
 * Reading it will not shortcut a single challenge. Here is why.
 *
 *   1. Flags are verified by comparing a salted SHA-256 digest. Digests are
 *      one way. Knowing the digest of flag_4 does not hand you flag_4.
 *
 *   2. The two payloads that sit behind the sudo gate, /root/root.txt and
 *      the flag checker's final reveal, ship as AES-256-GCM ciphertext.
 *      The key is PBKDF2-SHA256 over the sudo password, which is stored
 *      nowhere at all, not even as a hash. When you type the password we
 *      derive a key and try to decrypt. A valid GCM auth tag simultaneously
 *      proves the password was right and hands over the plaintext. One
 *      mechanism, two jobs, no secret to leak.
 *
 * The previous version of this site shipped an obfuscated bundle with the
 * flags sitting in plaintext inside it. Obfuscation is not a security
 * control, it is a speed bump. This is the honest version: the bundle is
 * readable, and it is readable precisely because there is nothing in it
 * worth hiding.
 *
 * The one exception, stated plainly rather than hidden: flag_2 is embedded
 * in the fake /etc/passwd because reading that file IS the challenge. Any
 * purely client side CTF has to ship the content it asks you to find. That
 * one is honestly free if you read the source, and always was.
 *
 * Constants below are generated by tools/gen-ctf-constants.py, which lives
 * outside this repository and holds the only plaintext copy. Do not hand
 * edit them. Regenerate if a flag ever changes.
 * ========================================================================= */

(function (global) {
  'use strict';

  /* ---------------- generated constants, do not hand edit ---------------- */

  const CTF = {
    "hashSalt": "r00tp4rv|ctf|v2|",
    "kdf": {
      "salt": "rg2YaXUdsfjx6oIn5VuTpA==",
      "iterations": 200000,
      "hash": "SHA-256"
    },
    "slots": [
      { "id": "f1", "label": "flag_1", "hint": "encoding", "digest": "12302482457478c34e24f4cca7a43bb175d5617b8c083da171d58f65fd8220dd" },
      { "id": "f2", "label": "flag_2", "hint": "shadows",  "digest": "2ada206054a9981c0439e9dc0af53bb1f636574f1c30c762b6122c54305aa6a2" },
      { "id": "f3", "label": "flag_3", "hint": "privesc",  "digest": "88dee7b40cdbbd5f7102c68dc79bf910c9c6bff7b85105c14c5d94902c552ce2" },
      { "id": "f4", "label": "flag_4", "hint": "stego",    "digest": "d5ed11c7fda2d79568f4f3f49801a795940e00768eb3488607e9f7d9d4ad5f7d" },
      { "id": "f5", "label": "flag_5", "hint": "osint",    "digest": "d7afeb44f8c91c94026f7fdff39bfc714edceb9e13cdd378279218f8c10f6a2d" }
    ],
    "bonus": { "id": "bonus", "label": "bonus", "hint": "xp", "digest": "7930b79c84c8e933002b1f051dc255c9254f2c3cb3f06312ef6d10f1503a0ff1" },
    "decoys": [
      "a52eb5fa3aac37a7c2109d08c68d60261bd242aebf92c0b2935d62a5557414ec",
      "81e97416cbd4036085afff473c138161f281380a0e966b99f1008173fa24f2c3",
      "483fcbc1393dcacea7ae28be93e849769debffddc52e03a16a8e6089663c38fb",
      "2051f873fed08baf67f9b2e22fc0f2ee603c8a4a02a507bf88b0ca3a05df7522"
    ],
    "vault": {
      "root_txt":     { "iv": "E5UZr6CPzL3mlpj/", "ct": "lTt/KVNDBenxlWW3gsux4ZEjvGfirtrQXRzGy1UM83IAryyctJlg4g==" },
      "final_reveal": { "iv": "0iRizQ04ELYZc2xI", "ct": "7pBoNbEJdae08NmhrbB/RJRytMzuMeIB4wIumbzronBr7aAuoXtM1z++RNo=" }
    }
  };

  /* ---------------------------- crypto helpers --------------------------- */

  const subtle = (global.crypto && global.crypto.subtle) || null;

  // WebCrypto needs a secure context. https and localhost qualify, file://
  // does not. Serve locally with `python3 -m http.server` when developing.
  const CRYPTO_AVAILABLE = !!subtle;

  function b64ToBytes(s) {
    const bin = atob(s);
    const out = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    return out;
  }

  /*
   * Normalize before hashing so a flag pasted from a PDF, a Discord message
   * or a mobile keyboard still matches. Strips zero width characters, control
   * characters and non breaking spaces, folds Unicode to NFKC, trims ends.
   * Case is preserved: these flags are case sensitive by design.
   */
  function normalizeFlag(s) {
    if (typeof s !== 'string') s = String(s || '');
    if (s.normalize) s = s.normalize('NFKC');
    s = s.replace(/[\u200B-\u200D\uFEFF]/g, '');   // zero width space, ZWNJ, ZWJ, BOM
    s = s.replace(/[\x00-\x1F\x7F]/g, '');          // control characters
    s = s.replace(/\u00A0/g, ' ');            // non breaking space
    return s.replace(/^\s+|\s+$/g, '');
  }

  async function sha256Hex(str) {
    const buf = await subtle.digest('SHA-256', new TextEncoder().encode(str));
    return Array.from(new Uint8Array(buf))
      .map(function (b) { return b.toString(16).padStart(2, '0'); })
      .join('');
  }

  async function flagDigest(value) {
    return sha256Hex(CTF.hashSalt + normalizeFlag(value));
  }

  async function deriveVaultKey(password) {
    const base = await subtle.importKey(
      'raw', new TextEncoder().encode(password), 'PBKDF2', false, ['deriveKey']
    );
    return subtle.deriveKey(
      {
        name: 'PBKDF2',
        salt: b64ToBytes(CTF.kdf.salt),
        iterations: CTF.kdf.iterations,
        hash: CTF.kdf.hash
      },
      base,
      { name: 'AES-GCM', length: 256 },
      false,
      ['decrypt']
    );
  }

  /* Returns plaintext on success, null when the auth tag fails. A null here
   * is the authoritative "wrong password" signal. There is nothing else to
   * compare against, which is the point. */
  async function openVault(key, name) {
    const blob = CTF.vault[name];
    if (!blob) return null;
    try {
      const pt = await subtle.decrypt(
        { name: 'AES-GCM', iv: b64ToBytes(blob.iv) }, key, b64ToBytes(blob.ct)
      );
      return new TextDecoder().decode(pt);
    } catch (e) {
      return null;
    }
  }

  /* Cache the derived key for the session so we pay the 200k PBKDF2 rounds
   * once rather than on every gated read. Never persisted. */
  let sessionKey = null;

  async function unlockWithPassword(password) {
    if (!CRYPTO_AVAILABLE) return null;
    const key = await deriveVaultKey(password);
    const probe = await openVault(key, 'root_txt');
    if (probe === null) return null;
    sessionKey = key;
    return probe;
  }

  async function readVault(name) {
    if (!sessionKey) return null;
    return openVault(sessionKey, name);
  }

  function isUnlocked() { return sessionKey !== null; }

  function lock() { sessionKey = null; }

  /* ----------------------------- progress store -------------------------- */

  /*
   * Local only, by design. There is no server and no leaderboard, so anyone
   * can hand edit localStorage to fake 5/5. That is fine: the only person
   * they would be cheating is themselves. Nothing here gates access to a
   * flag, it purely records what the player has already found.
   */
  const STORE_KEY = 'r00tp4rv.ctf.v2';

  function readStore() {
    try {
      const raw = global.localStorage.getItem(STORE_KEY);
      if (!raw) return { captured: {}, completedAt: null };
      const parsed = JSON.parse(raw);
      if (!parsed || typeof parsed !== 'object') throw new Error('shape');
      return {
        captured: (parsed.captured && typeof parsed.captured === 'object') ? parsed.captured : {},
        completedAt: parsed.completedAt || null
      };
    } catch (e) {
      // Corrupt or unavailable storage must never break the site.
      return { captured: {}, completedAt: null };
    }
  }

  function writeStore(state) {
    try {
      global.localStorage.setItem(STORE_KEY, JSON.stringify(state));
    } catch (e) {
      /* private browsing, quota, storage disabled: play on without persistence */
    }
  }

  const Progress = {
    all: function () { return CTF.slots.slice(); },
    bonusSlot: function () { return Object.assign({}, CTF.bonus); },
    state: readStore,

    has: function (id) { return !!readStore().captured[id]; },

    count: function () {
      const c = readStore().captured;
      return CTF.slots.filter(function (s) { return !!c[s.id]; }).length;
    },

    total: function () { return CTF.slots.length; },

    hasBonus: function () { return !!readStore().captured[CTF.bonus.id]; },

    isComplete: function () { return Progress.count() === CTF.slots.length; },

    /* Returns true when this call is what completed the set, so the caller
     * knows whether to fire the celebration exactly once. */
    mark: function (id) {
      const state = readStore();
      if (state.captured[id]) return false;
      const wasComplete = Progress.isComplete();
      state.captured[id] = new Date().toISOString();
      if (!state.completedAt) {
        const now = CTF.slots.every(function (s) { return !!state.captured[s.id]; });
        if (now) state.completedAt = new Date().toISOString();
      }
      writeStore(state);
      return !wasComplete && Progress.isComplete();
    },

    reset: function () {
      try { global.localStorage.removeItem(STORE_KEY); } catch (e) {}
    }
  };

  /* ------------------------- single submission path ---------------------- */

  /*
   * Both the terminal `flag <value>` command and the flag checker card call
   * this. Previously there were two hardcoded flag lists that had already
   * drifted apart: the terminal accepted five flags, the card accepted four.
   * One path means they can never disagree again.
   *
   * Result kinds:
   *   captured  first time this flag has been seen, slot + completed
   *   already   correct, but already recorded
   *   bonus     the hidden xp.html flag
   *   decoy     one of the planted fakes
   *   password  the sudo password typed into the checker, reveals flag_5
   *   empty     nothing entered
   *   wrong     no match
   *   nocrypto  WebCrypto unavailable, cannot verify
   */
  async function submitFlag(rawValue, opts) {
    const options = opts || {};
    const value = normalizeFlag(rawValue);

    if (!value) return { kind: 'empty' };
    if (!CRYPTO_AVAILABLE) return { kind: 'nocrypto' };

    // The checker accepts the sudo password as an easter egg, which the RSA
    // side quest points at: "feed it the root password and uncover what it
    // hides". The terminal does not, hence the opt in.
    if (options.allowPassword) {
      const revealed = await (async function () {
        const key = await deriveVaultKey(value);
        return openVault(key, 'final_reveal');
      })();
      if (revealed !== null) {
        return { kind: 'password', reveal: revealed };
      }
    }

    const digest = await flagDigest(value);

    const slot = CTF.slots.find(function (s) { return s.digest === digest; });
    if (slot) {
      if (Progress.has(slot.id)) return { kind: 'already', slot: slot };
      const completed = Progress.mark(slot.id);
      return { kind: 'captured', slot: slot, completed: completed };
    }

    if (digest === CTF.bonus.digest) {
      const known = Progress.has(CTF.bonus.id);
      if (!known) Progress.mark(CTF.bonus.id);
      return { kind: 'bonus', slot: CTF.bonus, already: known };
    }

    if (CTF.decoys.indexOf(digest) !== -1) return { kind: 'decoy' };

    return { kind: 'wrong' };
  }

  /* -------------------------------- exports ------------------------------ */

  global.CTFEngine = {
    slots: CTF.slots,
    bonus: CTF.bonus,
    cryptoAvailable: CRYPTO_AVAILABLE,
    normalizeFlag: normalizeFlag,
    submitFlag: submitFlag,
    unlockWithPassword: unlockWithPassword,
    readVault: readVault,
    isUnlocked: isUnlocked,
    lock: lock,
    Progress: Progress
  };

})(window);
